import requests, time, json

DETAIL_URL = "https://psi.nasa.gov/geode-py/ws/repo/investigations/{id}"
FILE_BASE  = "https://psi.nasa.gov"   # prefix for remote_url paths

print("📄 Fetching full details per investigation...\n")

for i, inv in enumerate(investigations):
    psi_id = inv["id"]
    try:
        r = requests.get(DETAIL_URL.format(id=psi_id), timeout=30)
        if r.status_code == 200:
            d = r.json()
            inv["_detail"] = d

            # ---- Core text fields (overwrite with full versions) ----
            inv["objectives"]      = d.get("objective", inv.get("objectives", ""))
            inv["approach"]        = d.get("approach", inv.get("approach", ""))
            inv["hypothesis"]      = d.get("hypothesis", "")
            inv["research_impacts"] = d.get("researchImpacts", "")
            inv["doi"]             = d.get("doi", "")
            inv["license"]         = d.get("licenseName", "")

            # ---- PI / contacts ----
            contacts = d.get("contacts", []) or []
            pi_list, all_contacts = [], []
            for c in contacts:
                name = f"{c.get('firstName','')} {c.get('midInitials','')} {c.get('lastName','')}".strip()
                affil = c.get("affiliation", "")
                roles = [r.get("annotationValue", "") for r in c.get("roles", [])]
                role_str = ", ".join(roles)
                all_contacts.append(f"{name} ({affil}) — {role_str}")
                if any("Principal Investigator" in r for r in roles):
                    pi_list.append(f"{name} ({affil})")
            if pi_list:
                inv["pi"] = "; ".join(pi_list)
            inv["contacts"] = all_contacts

            # ---- Data files (merge 'added' + 'modified') ----
            files = (d.get("added", []) or []) + (d.get("modified", []) or [])
            file_records = []
            for f in files:
                if not f.get("visible", True):
                    continue
                file_records.append({
                    "name":        f.get("file_name", ""),
                    "size_bytes":  f.get("file_size", 0),
                    "subcategory": f.get("subcategory", ""),
                    "path":        f.get("remote_path", ""),
                    "url":         FILE_BASE + f.get("remote_url", "") if f.get("remote_url") else "",
                    "restricted":  f.get("restricted", False),
                })
            inv["files"] = file_records

            # Categorize files
            inv["csv_files"]  = [f for f in file_records if f["name"].lower().endswith(".csv")]
            inv["pdf_files"]  = [f for f in file_records if f["name"].lower().endswith(".pdf")]
            inv["xlsx_files"] = [f for f in file_records if f["name"].lower().endswith(".xlsx")]

            # ---- Publications ----
            pubs = d.get("publications", []) or []
            pub_records = []
            for p in pubs:
                pub_records.append({
                    "title":   p.get("title", ""),
                    "authors": p.get("authorList", ""),
                    "doi":     p.get("doi", ""),
                    "status":  (p.get("status", {}) or {}).get("annotationValue", ""),
                })
            inv["publications"] = pub_records

            print(f"  [{i+1:2}/{len(investigations)}] ✅ {psi_id}  "
                  f"({len(file_records)} files · {len(inv['csv_files'])} CSV · "
                  f"{len(inv['pdf_files'])} PDF · {len(pub_records)} pubs)")
        else:
            print(f"  [{i+1:2}/{len(investigations)}] ⚠️  {psi_id} → HTTP {r.status_code}")
    except Exception as e:
        print(f"  [{i+1:2}/{len(investigations)}] ❌ {psi_id}: {e}")

    time.sleep(0.25)

