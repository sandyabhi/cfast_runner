def format_person(person):
    """Convert PSI person dict → 'First Middle Last' string."""
    if not person:
        return ""
    if isinstance(person, list):
        return "; ".join(format_person(p) for p in person)
    first  = person.get("First Name", "").strip()
    middle = person.get("Middle Initials", "").strip()
    last   = person.get("Last Name", "").strip()
    return " ".join(x for x in [first, middle, last] if x)

