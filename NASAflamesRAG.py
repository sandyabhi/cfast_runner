def format_person1(person):
    """
    PSI returns Person as either:
      - a dict with single string values (one person)
      - a dict where each field is a LIST (multiple people, parallel arrays)
      - a list of dicts (rare)
    """
    if not person:
        return ""

    # Case 1: list of dicts
    if isinstance(person, list):
        return "; ".join(format_person(p) for p in person if p)

    # Case 2: dict with parallel arrays (multiple people)
    first  = person.get("First Name", "")
    middle = person.get("Middle Initials", "")
    last   = person.get("Last Name", "")

    if isinstance(first, list) or isinstance(last, list):
        # Normalize to lists of equal length
        firsts  = first  if isinstance(first,  list) else [first]
        middles = middle if isinstance(middle, list) else [middle] * len(firsts)
        lasts   = last   if isinstance(last,   list) else [last]   * len(firsts)
        # Pad shorter arrays
        n = max(len(firsts), len(lasts))
        firsts  += [""] * (n - len(firsts))
        middles += [""] * (n - len(middles))
        lasts   += [""] * (n - len(lasts))
        people = []
        for f, m, l in zip(firsts, middles, lasts):
            name = " ".join(x.strip() for x in [f, m, l] if x and x.strip())
            if name:
                people.append(name)
        return "; ".join(people)

    # Case 3: single person as dict of strings
    name = " ".join(x.strip() for x in [first, middle, last] if x and str(x).strip())
    return name

