# ---- Helpers ----
def format_files(files, label, limit=15):
    if not files: return f"No {label} available."
    lines = []
    for f in files[:limit]:
        subcat = f" [{f['subcategory']}]" if f.get("subcategory") else ""
        size_kb = f.get("size_bytes", 0) / 1024
        lines.append(f"  • {f['name']}{subcat}  ({size_kb:.1f} KB)")
    if len(files) > limit:
        lines.append(f"  ... and {len(files) - limit} more")
    return "\n".join(lines)

def format_pubs(pubs, limit=15):
    if not pubs: return "No publications listed."
    lines = []
    for p in pubs[:limit]:
        doi = f" — DOI: {p['doi']}" if p.get('doi') else ""
        lines.append(f"  • {p['title']}\n    Authors: {p['authors']}{doi}")
    return "\n".join(lines)

